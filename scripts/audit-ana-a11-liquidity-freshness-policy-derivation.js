'use strict';
const fs=require('fs');const path=require('path');const root=path.resolve(__dirname,'..');
const c=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a11-liquidity-freshness-policy-derivation.json'),'utf8'));
const a07=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a07-freshness-window-authority.json'),'utf8'));
const a10=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a10-cat-liquidity-projection.json'),'utf8'));
const matrix=JSON.parse(fs.readFileSync(path.join(root,'config','domain-completion-matrix.json'),'utf8'));
const checks=[];const check=(n,v)=>checks.push({name:n,passed:Boolean(v)});
check('contract id',c.contractId==='ana-a11-liquidity-freshness-policy-derivation-v1');
check('metric exact',c.metricKey==='liquidity.active_service_seconds'&&c.metricVersion==='v1');
check('repository only',c.scope==='repository_only');
check('root cause is cadence',c.rootCause?.missingNumberIsNotRootCause===true);
check('formula exact',c.thresholdDerivation?.formula==='maxLagSeconds = windowStepSeconds + projectionDelaySloSeconds');
check('no implicit grace',c.thresholdDerivation?.extraGrace?.implicitGraceAllowed===false&&c.thresholdDerivation?.extraGrace?.recoveryBudgetMayBeAdded===false);
check('source lag separate',c.thresholdDerivation?.sourceWatermarkLagAddedToThreshold===false);
check('values unset',c.currentDecision?.windowStepSeconds===null&&c.currentDecision?.projectionDelaySloSeconds===null&&c.currentDecision?.maxLagSeconds===null);
check('policy insert unauthorized',c.currentDecision?.policyInsertAuthorized===false);
check('A07 threshold pending',a07.thresholdAuthority?.defaultMaxLagSeconds===null&&a07.thresholdAuthority?.status==='pending_versioned_metric_policy');
check('A10 still fail closed',a10.freshnessDependency?.metricThresholdStatus!=='active'&&a10.runtimeImplementation?.liquidityPolicyInserted===false);
const ana=matrix.domains.find(d=>d.id==='ANA-001');
check('ANA no cron authority',Array.isArray(ana?.crons)&&ana.crons.length===0);
check('ANA remains 3/6',ana?.maturity===3);
check('A11 registered',ana?.requiredPaths?.includes('config/ana-a11-liquidity-freshness-policy-derivation.json')&&ana?.tests?.includes('audit:ana-a11-liquidity-freshness-policy-derivation'));
Object.entries(c.prohibitedEffects||{}).forEach(([k,v])=>check('effect '+k,v===false));
const failed=checks.filter(x=>!x.passed).map(x=>x.name);
console.log(JSON.stringify({contractId:c.contractId,total:checks.length,passed:checks.length-failed.length,failed:failed.length,status:failed.length?'failed':'passed',failedChecks:failed},null,2));
if(failed.length)process.exitCode=1;

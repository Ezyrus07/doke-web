const fs = require('fs');
const assert = require('assert');
const root = process.cwd();
const html = fs.readFileSync(`${root}/notificacoes.html`, 'utf8');
const feature = fs.readFileSync(`${root}/assets/js/features/in-app-notifications.js`, 'utf8');
const delivery = fs.readFileSync(`${root}/assets/js/core/notification-delivery.js`, 'utf8');
const page = fs.readFileSync(`${root}/assets/js/pages/notificacoes.js`, 'utf8');
assert(html.includes('data-notifications-settings-toggle'));
assert(html.includes('data-notification-dnd-duration'));
assert(html.includes('data-notification-priority-min'));
['flushDigest','muteScope','getDeliveryManager'].forEach((token)=>assert(feature.includes(token), token));
['dndUntil','priorityMin','mutedScopes','QUEUE_DIGEST','ALLOW_TOAST','notification_delivery'].forEach((token)=>assert(delivery.includes(token), token));
assert(page.includes('data-notification-unmute-scope'));
console.log('Notification delivery controls contract: OK');

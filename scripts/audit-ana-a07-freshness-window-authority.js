'use strict';
const fs=require('fs');
const path=require('path');
const f=require('../backend/modules/analytics/freshness-window-authority');
const root=path.resolve(__dirname,'..');
const c=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a07-freshness-window-authority.json'),'utf8'));
const a04=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a04-marketplace-funnel-health-projections.json'),'utf8'));
const a05=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a05-reconciliation-data-quality.json'),'utf8'));
const a06=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a06-data-quality-ownership-gates.json'),'utf8'));
const matrix=JSON.parse(fs.readFileSync(path.join(root,'config','domain-completion-matrix.json'),'utf8'));
const checks=[];const check=(name,value)=>checks.push({name,passed:Boolean(value)});
check('contract id',f.CONTRACT_ID===c.contractId);
check('repository only',c.scope==='repository_only');
check('states',JSON.stringify(f.FRESHNESS_STATES)===JSON.stringify(c.freshnessStates));
check('no implicit threshold',c.thresholdAuthority?.defaultMaxLagSeconds===null&&c.evaluation?.implicitDefaultMaxLagForbidden===true);
check('A05 dataThrough precedent',a05.invariants.includes('freshness is based on dataThrough rather than computedAt alone'));
check('A06 freshness remains open',a06.stagingEvidence?.freshnessSelectionAuthorityClosed===false);
check('all A04 metrics mapped',a04.metrics.every((m)=>c.metricDependencies.some((d)=>d.metricKey===m.key)));
check('metric map exact size',c.metricDependencies.length===a04.metrics.length);
check('no older healthy fallback',c.windowSelection?.olderHealthyFallbackAllowed===false);
check('computedAt not authority',c.dataThroughAuthority?.computedAtDefinesFreshness===false);
check('max event time not authority',c.dataThroughAuthority?.maxEventTimestampDefinesFreshness===false);
check('empty window can be fresh',c.dataThroughAuthority?.emptyWindowMayStillBeFresh===true);
check('maturity unchanged',c.maturity?.before===3&&c.maturity?.after===3);
Object.entries(c.prohibitedEffects||{}).forEach(([k,v])=>check('effect '+k,v===false));
const ana=(matrix.domains||[]).find((d)=>d.id==='ANA-001');
check('ANA stays 3/6',ana?.maturity===3);
check('A07 config in matrix',ana?.requiredPaths?.includes('config/ana-a07-freshness-window-authority.json'));
check('A07 module in matrix',ana?.requiredPaths?.includes('backend/modules/analytics/freshness-window-authority.js'));
check('A07 audit registered',ana?.tests?.includes('audit:ana-a07-freshness-window-authority'));
check('A07 test registered',ana?.tests?.includes('test:ana-a07-freshness-window-authority'));
const failed=checks.filter((x)=>!x.passed).map((x)=>x.name);
console.log(JSON.stringify({contractId:c.contractId,total:checks.length,passed:checks.length-failed.length,failed:failed.length,status:failed.length?'failed':'passed',failedChecks:failed},null,2));
if(failed.length)process.exitCode=1;

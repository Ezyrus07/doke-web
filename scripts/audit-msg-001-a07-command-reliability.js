'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { isNumericSemanticVersionAtLeast } = require('./lib/semantic-version');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const assert = (condition, message) => { if (!condition) throw new Error('MSG-A07 audit failed: ' + message); };
const config = JSON.parse(read('config/msg-001-a07-command-reliability.json'));
const executor = read('assets/js/services/message-command-executor.js');
const messageService = read('assets/js/services/message-service.js');
const provider = read('assets/js/services/api-repository-provider.js');
const registry = read('backend/shared/http/route-registry.js');
const backend = read('backend/modules/messaging/messaging-service.js');
const handlers = read('backend/modules/messaging/route-handlers.js');
const matrix = JSON.parse(read('config/domain-completion-matrix.json'));
const msg = matrix.domains.find((domain) => domain.id === 'MSG-001');
const workflow = read('.github/workflows/msg-001-a07-command-reliability.yml');
assert(config.contractVersion === 'msg-a07-command-reliability-v1', 'contract version');
assert(config.status === 'repository_only_command_reliability_ready_not_deployed', 'repository-only status');
assert(config.retry.maxAttempts === 3, 'retry must be bounded');
assert(config.effects.stagingReads === 0 && config.effects.stagingMutations === 0, 'staging effects');
assert(executor.includes('x-idempotency-key') === false, 'executor must not implement transport headers');
assert(executor.includes('maxAttempts: 3'), 'max attempts contract');
assert(executor.includes('claimSideEffects'), 'side-effect dedupe missing');
assert(executor.includes('DOKE_MESSAGES_COMMAND_ACK_INVALID'), 'ack guard missing');
assert(!executor.includes('localStorage'), 'browser persistence prohibited');
assert(messageService.includes('messageCommandExecutor'), 'service executor wiring missing');
assert(messageService.includes('claimSideEffects'), 'service side-effect claim missing');
assert(provider.includes("options.headers['x-idempotency-key']"), 'idempotency header missing');
assert(provider.includes("options.headers['x-request-id']"), 'request id header missing');
assert(registry.includes("route('messages.remove'"), 'remove route missing');
for (const route of ['messages.send', 'messages.remove', 'messages.markRead']) { const line = registry.split('\n').find((entry) => entry.includes("route('" + route + "'")); assert(line && line.includes('true, true, false, true'), route + ' reliability flags'); }
assert(backend.includes('async function removeMessage'), 'server remove command missing');
assert(backend.includes("status: 'removed'"), 'remove tombstone missing');
assert(handlers.includes('createMessagingCommandHandler'), 'ack wrapper missing');
assert(handlers.includes("status: replayed ? 'replayed' : 'accepted'"), 'ack states missing');
assert(isNumericSemanticVersionAtLeast(matrix.version, '1.3.84'), 'matrix version must be at least 1.3.84');
assert(msg && msg.tests.includes('audit:msg-001-a07-command-reliability'), 'matrix audit');
assert(msg.tests.includes('test:msg-001-a07-command-reliability-runtime'), 'matrix runtime');
assert(workflow.includes('permissions:\n  contents: read'), 'workflow read-only');
for (const fragment of ['contents: write', 'secrets.', 'SUPABASE_ACCESS_TOKEN', 'SUPABASE_DB_PASSWORD', 'psql ', 'curl ', 'git push']) assert(!workflow.includes(fragment), 'prohibited workflow fragment ' + fragment);
console.log('MSG-A07 command reliability audit passed.');

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const realtime = fs.readFileSync(path.join(root, 'assets/js/features/chat-realtime-presence.js'), 'utf8');
const messages = fs.readFileSync(path.join(root, 'mensagens.html'), 'utf8');
const failures = [];
const check = (label, condition) => { if (!condition) failures.push(label); };

check('realtime render uses idempotent HTML writes', realtime.includes('function setHtmlIfChanged'));
check('realtime render uses idempotent text writes', realtime.includes('function setTextIfChanged'));
check('presence line avoids unconditional innerHTML writes', /setHtmlIfChanged\(line, html\)/.test(realtime));
check('typing indicator avoids unconditional DOM rewrites', /setHtmlIfChanged\(node,/.test(realtime));
check('read receipt reuses the receipt mounted in the active bubble', /receipts\.find\(function \(node\) \{ return node\.parentElement === bubble; \}\)/.test(realtime));
check('read receipt no longer removes and recreates every receipt on every render', !/querySelectorAll\('\[data-realtime-read-receipt\]'\)\.forEach\(function \(node\) \{ node\.remove\(\); \}\)/.test(realtime));
check('observer ignores mutations generated by realtime nodes', realtime.includes('function hasExternalDomMutation'));
check('observer coalesces external DOM synchronization into one animation frame', realtime.includes('function scheduleDomSync'));
check('observer does not monitor characterData generated by its own labels', /observer\.observe\(document\.body, \{ childList: true, subtree: true \}\)/.test(realtime));
check('messages invalidates the previous realtime presence cache', messages.includes('chat-realtime-presence.js?v=20260714-messages-startup-loop-v2'));

if (failures.length) {
  console.error('Messages startup hydration stability contract failed:');
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exit(1);
}

console.log('Messages startup hydration stability contract: OK');

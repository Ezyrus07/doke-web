'use strict';
const fs=require('fs');
const path=require('path');
const r=require('../backend/modules/analytics/retention-cohort-projection');
const root=path.resolve(__dirname,'..');
const c=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a08-retention-cohort-projection.json'),'utf8'));
const a04=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a04-marketplace-funnel-health-projections.json'),'utf8'));
const a07=JSON.parse(fs.readFileSync(path.join(root,'config','ana-a07-freshness-window-authority.json'),'utf8'));
const matrix=JSON.parse(fs.readFileSync(path.join(root,'config','domain-completion-matrix.json'),'utf8'));
const checks=[];const check=(n,v)=>checks.push({name:n,passed:Boolean(v)});
check('contract id',r.CONTRACT_ID===c.contractId);
check('repository only',c.scope==='repository_only');
check('two metrics',Object.keys(r.METRICS).length===2&&c.metrics.length===2);
for(const key of Object.keys(r.METRICS))check('A04 declares '+key,a04.metrics.some((m)=>m.key===key));
check('A07 dependency',c.freshnessDependency?.contract==='ANA-A07'&&a07.contractId==='ana-a07-freshness-window-authority-v1');
check('no repeat segment match requirement',c.segmentation?.repeatMustMatchInitialSegment===false);
check('anonymous stitching prohibited',c.sourceAuthority?.anonymousIdentityStitchingAllowed===false);
check('runtime authority false',c.authority?.runtimeProjectionAuthority===false);
check('maturity unchanged',c.maturity?.before===3&&c.maturity?.after===3);
Object.entries(c.prohibitedEffects||{}).forEach(([k,v])=>check('effect '+k,v===false));
const ana=(matrix.domains||[]).find((d)=>d.id==='ANA-001');
check('ANA stays 3/6',ana?.maturity===3);
check('A08 config in matrix',ana?.requiredPaths?.includes('config/ana-a08-retention-cohort-projection.json'));
check('A08 module in matrix',ana?.requiredPaths?.includes('backend/modules/analytics/retention-cohort-projection.js'));
check('A08 audit registered',ana?.tests?.includes('audit:ana-a08-retention-cohort-projection'));
check('A08 test registered',ana?.tests?.includes('test:ana-a08-retention-cohort-projection'));
const failed=checks.filter((x)=>!x.passed).map((x)=>x.name);
console.log(JSON.stringify({contractId:c.contractId,total:checks.length,passed:checks.length-failed.length,failed:failed.length,status:failed.length?'failed':'passed',failedChecks:failed},null,2));
if(failed.length)process.exitCode=1;
